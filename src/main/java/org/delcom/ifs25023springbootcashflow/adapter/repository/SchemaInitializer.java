package org.delcom.ifs25023springbootcashflow.adapter.repository;

import javax.sql.DataSource;
import java.sql.Connection;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.List;

/** Membuat tabel bila belum ada. Aman dijalankan berulang kali setiap aplikasi start. */
public final class SchemaInitializer {

    private static final List<String> STATEMENTS = List.of(
            """
            CREATE TABLE IF NOT EXISTS users (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                username VARCHAR(100) NOT NULL UNIQUE,
                password_hash VARCHAR(255) NOT NULL,
                full_name VARCHAR(200) NOT NULL,
                role VARCHAR(20) NOT NULL,
                photo_path VARCHAR(500)
            )
            """,
            """
            CREATE TABLE IF NOT EXISTS transactions (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                user_id INTEGER NOT NULL,
                description TEXT NOT NULL,
                amount BIGINT NOT NULL,
                type VARCHAR(20) NOT NULL,
                proof_path VARCHAR(500),
                created_at TIMESTAMP NOT NULL,
                CONSTRAINT fk_transactions_user FOREIGN KEY (user_id) REFERENCES users(id)
            )
            """,
            "CREATE INDEX IF NOT EXISTS idx_transactions_user ON transactions(user_id)"
    );

    private SchemaInitializer() {
    }

    public static void initialize(DataSource dataSource) {
        try (Connection connection = dataSource.getConnection();
             Statement statement = connection.createStatement()) {
            for (String sql : STATEMENTS) {
                statement.execute(sql);
            }
        } catch (SQLException e) {
            throw new IllegalStateException("Gagal menyiapkan skema database", e);
        }
    }
}
